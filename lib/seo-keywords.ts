// Ключевые слова под органику Казахстана (SEO-подготовка 19.07).
// Логика: у нас 57 обзоров ниш — каждый лендинг под длинный хвост
// «открыть <нишу> в Казахстане / окупаемость / сколько стоит». Заголовок и
// описание генерятся из названия ниши по шаблону, ключи собираются массивом.
// Google ранжирует по <title>/<h1>/описанию/контенту, не по meta keywords —
// поэтому ключи идут в ЗАГОЛОВОК и ОПИСАНИЕ, а keywords[] держим для полноты.

const YEAR = "2026";

// Родительное «нишу»: для шаблона «открыть X». Грубая русская эвристика по
// окончанию; спорные — в исключениях. Не идеально грамматически, но для title
// достаточно, а точные формы правит редактор в исключениях по мере надобности.
const GENITIVE_FIX: Record<string, string> = {
  "Кофейня": "кофейню", "Пекарня": "пекарню", "Столовая": "столовую",
  "Аптека": "аптеку", "Автомойка": "автомойку", "Барбершоп": "барбершоп",
  "Автосервис": "автосервис", "Салон красоты": "салон красоты",
  "Фитнес-зал": "фитнес-зал", "Кинотеатр": "кинотеатр",
};
function nicheAccusative(title: string): string {
  return GENITIVE_FIX[title] ?? title.toLowerCase();
}

/** SEO-метаданные обзора ниши: заголовок и описание под коммерческий хвост. */
export function nicheSeo(title: string, blurb: string) {
  const acc = nicheAccusative(title);
  const seoTitle = `${title} в Казахстане ${YEAR}: окупаемость, риски, расчёт`;
  const firstSentence = (blurb.split(/(?<=[.!?])\s/)[0] || blurb).slice(0, 130);
  const description =
    `Бизнес-обзор ниши «${title}» по данным БНС, НБРК и 2ГИС: стартовые ` +
    `вложения, точка безубыточности, окупаемость, сезонность и риски. ${firstSentence}`;
  const keywords = [
    `открыть ${acc} в Казахстане`,
    `${title.toLowerCase()} бизнес-план`,
    `${title.toLowerCase()} окупаемость`,
    `сколько стоит открыть ${acc}`,
    `${title.toLowerCase()} рентабельность`,
    `${title.toLowerCase()} с нуля`,
    `бизнес-идея ${title.toLowerCase()} Казахстан`,
  ];
  return { seoTitle, description, keywords };
}

